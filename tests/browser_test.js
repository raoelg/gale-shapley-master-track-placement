// Headless browser smoke test of index.html (+ byte comparison of the downloads with R's write.csv output)
const { chromium } = require('playwright-core');
const fs = require('fs'), path = require('path');
const exe = process.env.CHROME || '/Applications/Brave Browser.app/Contents/MacOS/Brave Browser';
const caseDir = path.join(__dirname, 'cases', process.argv[2] || 'c01_small_csv');
const appFile = fs.readdirSync(caseDir).find(f => /^applications\./.test(f));
const quotaFile = fs.readdirSync(caseDir).find(f => /^quota\./.test(f));
(async () => {
  const browser = await chromium.launch({ executablePath: exe, headless: true });
  const ctx = await browser.newContext({ acceptDownloads: true });
  const page = await ctx.newPage();
  const problems = [];
  page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') problems.push(m.type() + ': ' + m.text()); });
  page.on('pageerror', e => problems.push('pageerror: ' + e.message));
  await page.goto('file://' + path.join(__dirname, 'index.html'));
  await page.waitForFunction(() => window.OMTP && window.XLSX && window.Chart);
  await page.setInputFiles('#file1', path.join(caseDir, appFile));
  await page.waitForSelector('#contents0 table tbody tr');
  await page.setInputFiles('#file3', path.join(caseDir, quotaFile));
  await page.waitForSelector('#contents3 table tbody tr');
  const report = {};
  report.mapping = await page.evaluate(() => ['student', 'track', 'preference', 'qualification'].map(id => document.getElementById(id).value));
  report.appsInfo = await page.textContent('#contents0 .tbl-info');
  report.quotaHeader = await page.$$eval('#contents3 th', th => th.map(t => t.textContent));
  await page.click('button[data-tab="tab-result"]');
  report.resultInfo = await page.textContent('#myText .tbl-info');
  const dl1 = await Promise.all([page.waitForEvent('download'), page.click('#downloadData')]).then(([d]) => d);
  const f1 = path.join(__dirname, 'browser_download.csv'); await dl1.saveAs(f1);
  report.downloadName = dl1.suggestedFilename();
  await page.click('button[data-tab="tab-summary"]');
  report.admissionBlocks = await page.$$eval('#collegeAdmissions .adm h6', h => h.map(x => x.textContent));
  report.chartsDrawn = await page.evaluate(() => ['summary', 'summary2'].map(id => !!Chart.getChart(id)));
  await page.click('button[data-tab="tab-details"]');
  report.detailsInfo = await page.textContent('#details .tbl-info');
  await page.click('button[data-tab="tab-waitlist"]');
  await page.waitForSelector('#waitlist table', { timeout: 60000 });
  report.waitlistInfo = await page.textContent('#waitlist .tbl-info');
  await page.click('button[data-tab="tab-result"]');
  const dl2 = await Promise.all([page.waitForEvent('download'), page.click('#downloadData')]).then(([d]) => d);
  const f2 = path.join(__dirname, 'browser_download_wl.csv'); await dl2.saveAs(f2);
  await page.click('button[data-tab="tab-summary"]');
  await page.screenshot({ path: path.join(__dirname, 'browser_summary.png'), fullPage: true });
  const r1 = path.join(caseDir, 'r_1', 'download.csv'), r2 = path.join(caseDir, 'r_1', 'download_wl.csv');
  report.downloadEqualsR = fs.existsSync(r1) && fs.readFileSync(f1).equals(fs.readFileSync(r1));
  report.downloadWlEqualsR = fs.existsSync(r2) && fs.readFileSync(f2).equals(fs.readFileSync(r2));
  report.consoleProblems = problems;
  console.log(JSON.stringify(report, null, 2));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
